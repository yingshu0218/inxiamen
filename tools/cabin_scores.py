def arrange(bpm, bars, harmony, style):
    beat = 60 / bpm
    events = []
    for number, (melody, chord) in enumerate(zip(bars, harmony, strict=True)):
        assert sum(duration for _, duration in melody) == 4, (number, melody)
        start = .09 + number * 4 * beat
        cursor = 0.0
        for pitch, duration in melody:
            if pitch:
                strength = .85 if cursor.is_integer() else .76
                events.append((start + cursor * beat, pitch, duration * beat * .94, strength))
            cursor += duration
        notes = VOICINGS[chord]
        if number == len(bars) - 1:
            pattern = [(i * .065, i, 3.7, .38) for i in range(4)]
        elif style == 'guitar':
            pattern = [(0, 0, 1.35, .53), (.52, 1, .82, .35), (1.02, 2, 1, .36), (1.57, 3, .75, .32),
                       (2, 0, 1, .40), (2.52, 2, .8, .33), (3, 3, .8, .36), (3.52, 1, .44, .30)]
        elif style == 'hymn':
            pattern = [(0, 0, 2.6, .50), (.52, 1, 1.55, .35), (1, 2, 1.35, .38), (1.52, 3, 1.25, .39),
                       (2.53, 1, 1.25, .31), (3.04, 2, .95, .34)]
        else:
            pattern = [(0, 0, 1.85, .50), (.54, 1, 1.2, .31), (1.04, 2, .92, .34), (1.55, 3, 1.55, .38),
                       (2.52, 2, 1.1, .32), (3.04, 1, .94, .31)]
        for when, index, length, volume in pattern:
            events.append((start + when * beat, notes[index], length * beat, volume))
    return events
